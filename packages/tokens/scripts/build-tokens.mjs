/**
 * Generates dist/tokens.css from src/tokens.json.
 *
 * One source, two ecosystems. Run via `pnpm --filter @janmaang/tokens build`,
 * which `make setup` invokes.
 *
 * The CSS half is what the web build consumes. Tailwind v4 is CSS-first: there
 * is no JS preset any more, so this emits an `@theme` block using Tailwind's
 * own namespaces (`--color-*`, `--font-*`, `--radius-*`, `--shadow-*`,
 * `--spacing-*`). Every key in tokens.json therefore becomes a utility class —
 * `--color-impact-wash` is `bg-impact-wash` — with no second place to register
 * it. apps/web/src/styles/globals.css imports this file.
 *
 * Because dist/ is generated and gitignored, this script has to run before
 * `next build` — a missing dist/tokens.css is a hard module-resolution
 * failure, not a silent fallback.
 *
 * TODO(tokens): also emit apps/mobile/lib/core/theme/janmaang_colors.dart, so
 * the Flutter constants come from this same source instead of being kept by
 * hand. That file is hand-maintained today; generating it is a separate change.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const tokens = JSON.parse(
  await readFile(join(root, "src", "tokens.json"), "utf8"),
);

/** camelCase and nested keys both flatten to kebab-case var segments. */
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Metadata keys in the JSON are documentation, not tokens. */
const isMeta = (key) => key.startsWith("$");

const theme = [];
const dark = [];

/**
 * A colour is either a plain value or a `{ light, dark }` pair. The pair form
 * is the only reason this can emit a second block.
 */
const pushColor = (name, value) => {
  if (value && typeof value === "object") {
    if (value.light !== undefined) theme.push([name, value.light]);
    if (value.dark !== undefined) dark.push([name, value.dark]);
    return;
  }
  theme.push([name, value]);
};

const walkColors = (node, path) => {
  for (const [key, value] of Object.entries(node)) {
    if (isMeta(key)) continue;
    const next = [...path, kebab(key)];
    // `{ light, dark }` is a leaf; anything else with children is a group.
    const isLeaf =
      typeof value !== "object" ||
      value.light !== undefined ||
      value.dark !== undefined;
    if (isLeaf) pushColor(`--color-${next.join("-")}`, value);
    else walkColors(value, next);
  }
};

walkColors(tokens.color ?? {}, []);

for (const [key, value] of Object.entries(tokens.font ?? {})) {
  if (isMeta(key)) continue;
  theme.push([`--font-${kebab(key)}`, value]);
}

for (const [key, value] of Object.entries(tokens.shadow ?? {})) {
  if (isMeta(key)) continue;
  theme.push([`--shadow-${kebab(key)}`, value]);
}

// Scales are authored as unitless numbers so the Dart side can use them too;
// CSS needs the px.
const px = (value) => (typeof value === "number" ? `${value}px` : value);

// Radius belongs in the theme: rounded-md should mean the design's md.
for (const [key, value] of Object.entries(tokens.radius ?? {})) {
  if (isMeta(key)) continue;
  theme.push([`--radius-${kebab(key)}`, px(value)]);
}

/*
 * Spacing does NOT go in the theme, and this is not an oversight.
 *
 * Tailwind v4 resolves `max-w-md`, `w-lg` and friends against --spacing-* as
 * well as --container-*, so emitting --spacing-md: 16px silently redefines
 * max-w-md from 28rem to 16px and collapses every centred column in the app.
 * It cost an afternoon to find. These stay plain custom properties: readable
 * from CSS and from the Dart generator, invisible to the utility scale.
 */
const scale = [];
for (const [key, value] of Object.entries(tokens.space ?? {})) {
  if (isMeta(key)) continue;
  scale.push([`--jm-space-${kebab(key)}`, px(value)]);
}

const block = (pairs, indent) =>
  pairs.map(([name, value]) => `${indent}${name}: ${value};`).join("\n");

/*
 * Dark overrides land on :root rather than inside @theme, because @theme may
 * not be nested in a media query. Tailwind's utilities reference the custom
 * property, so redefining it here is enough. The palette is light-only today —
 * this block stays empty until tokens.json carries `{ light, dark }` pairs.
 */
const css = `/* Generated by scripts/build-tokens.mjs from src/tokens.json — do not edit. */
@theme {
${block(theme, "  ")}
}

:root {
${block(scale, "  ")}
}
${
  dark.length
    ? `
@media (prefers-color-scheme: dark) {
  :root {
${block(dark, "    ")}
  }
}
`
    : ""
}`;

await mkdir(join(root, "dist"), { recursive: true });
await writeFile(join(root, "dist", "tokens.css"), css, "utf8");

console.log(
  `[tokens] wrote dist/tokens.css — ${theme.length} theme properties, ` +
    `${scale.length} spacing vars` +
    (dark.length ? `, ${dark.length} dark overrides` : ""),
);
